"""Session briefing, printed at the start of every Claude Code session (SessionStart hook).

It tells the session who its user is, whether the local copy is behind GitHub, the latest log
entries, open contract changes and requests, the user's next step, and the GitHub issues
addressed to them. Standard library only. It never fails: any error becomes a line of output.
"""

import json
import os
import re
import subprocess
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEAM = {"dnlsdn": "daniel", "fmdimarco": "fabio", "gioburattii": "gioia"}
STEP_PREFIX = {"daniel": "D", "fabio": "F", "gioia": "G"}
REPO = "dnlsdn/wikinews-search"


def run(args: list[str], timeout: int = 20) -> str:
    try:
        out = subprocess.run(
            args, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", timeout=timeout
        )
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


def section(text: str, title: str) -> str:
    match = re.search(rf"^## {re.escape(title)}\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    return match.group(1).strip() if match else ""


def main() -> None:
    print("SESSION BRIEFING (generated by scripts/briefing.py at session start)")
    print(f"Local time: {datetime.now():%A %d %B %Y, %H:%M}. Compare it with the timeline in PLAN.md.")

    login = os.environ.get("WIKISEARCH_GITHUB") or run(["gh", "api", "user", "--jq", ".login"])
    me = TEAM.get(login)
    if me:
        print(f"Your user is {me.capitalize()} (GitHub {login}). Brief: docs/briefs/{me}.md")
    else:
        print("Could not tell who your user is (GitHub CLI missing or not logged in): ask them, "
              "and tell them to run `gh auth login`, needed to read and send team messages.")

    run(["git", "fetch", "--quiet"], timeout=30)
    behind = run(["git", "rev-list", "--count", "HEAD..@{u}"])
    dirty = run(["git", "status", "--porcelain"])
    if behind and behind != "0":
        print(f"Your copy is {behind} commit(s) behind GitHub: run `git pull --rebase` before anything else.")
    if dirty:
        print(f"Uncommitted local changes: {len(dirty.splitlines())} file(s). Check `git status`.")

    state = (ROOT / "STATE.md").read_text(encoding="utf-8")
    log = section(state, "Log")
    titles = re.findall(r"^### (.+)$", log, re.M)[:5]
    print("\nLatest log entries in STATE.md (read the full entries):")
    for t in titles:
        print(f"  - {t}")
    for name in ("Contract changes",):
        body = section(state, name)
        if body and body != "None yet.":
            print(f"\n{name} in STATE.md:\n{body}")

    if me:
        plan = (ROOT / "PLAN.md").read_text(encoding="utf-8")
        steps = re.findall(rf"^- \[ \] \*\*({STEP_PREFIX[me]}\d+[^*]*)\*\*", plan, re.M)
        print(f"\nYour next unticked step in PLAN.md: {steps[0] if steps else 'none, all ticked'}")

    raw = run(["gh", "issue", "list", "-R", REPO, "--state", "open", "--limit", "50",
               "--json", "number,title,labels,author"])
    if not raw:
        print("\nGitHub issues: could not read them (is `gh auth login` done?).")
    else:
        issues = json.loads(raw)
        mine, shared = [], []
        for i in issues:
            labels = {lab["name"] for lab in i["labels"]}
            line = f"  #{i['number']} [{', '.join(sorted(labels))}] {i['title']} (from {i['author']['login']})"
            if me and f"for:{me}" in labels:
                mine.append(line)
            elif labels & {"blocker", "contract-change"}:
                shared.append(line)
        print("\nOpen issues addressed to you (read each with `gh issue view <n>`, deal with them first):")
        print("\n".join(mine) if mine else "  none")
        print("Open blockers and contract changes for everyone:")
        print("\n".join(shared) if shared else "  none")

    print("\nRules: CLAUDE.md. Work only on your brief; talk to the other sessions through GitHub "
          "issues, as described in CLAUDE.md, section 'Talking to the other sessions'.")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # the briefing must never block a session
        print(f"Briefing failed: {exc}. Read STATE.md, PLAN.md and your brief by hand.")
